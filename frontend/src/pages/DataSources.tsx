import { useMemo, useState } from 'react'
import { CartesianGrid, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import { Activity, Camera, Database, FileText, FlaskRound, Gauge, Search, Tag, Thermometer, Waves } from 'lucide-react'
import { api } from '@/api/client'
import type { Modality, StreamInfo } from '@/api/types'
import { PageBody, PageHeader } from '@/components/Layout'
import { Badge, Card, CardHeader, Mono, Skeleton, inputClass } from '@/components/ui/primitives'
import { Callout, EmptyState, ErrorState } from '@/components/ui/feedback'
import { CodeBlock, KeyValue } from '@/components/ui/content'
import { ChartTooltip } from '@/components/charts'
import { axisProps, CHART } from '@/components/chartTheme'
import { useApi } from '@/hooks/useApi'
import { cn, fmt } from '@/lib/utils'

const MODALITY_ICON: Partial<Record<Modality, typeof Activity>> = {
  temperature: Thermometer,
  pressure: Gauge,
  vibration: Waves,
  image: Camera,
  video: Camera,
  log: FileText,
}

function StreamPreview({ stream }: { stream: StreamInfo }) {
  const q = useApi(() => api.preview(stream.id, 120), [stream.id])
  const numeric = q.data?.every((p) => typeof p.value === 'number')
  return (
    <Card>
      <CardHeader title={stream.name} description={<Mono>{stream.id}</Mono>} actions={<Badge>{stream.modality}</Badge>} />
      <div className="space-y-4 p-4">
        <KeyValue
          items={[
            ['Source', <Mono key="s">{stream.source}</Mono>],
            ['Unit', stream.unit ?? '—'],
            ['Sample rate', stream.sample_hz != null ? `${stream.sample_hz} Hz` : '—'],
            ...(stream.description ? [['Description', stream.description] as [string, string]] : []),
          ]}
        />
        <Callout tone="warn" icon={<FlaskRound className="size-3.5" />} title="Synthetic preview">
          <Mono>GET /api/streams/{'{id}'}/preview</Mono> returns values generated by the plant simulator (a degrading press), not rows
          from the underlying dataset. The API has no raw-data inspection endpoint yet; the agent inspects raw data itself during design.
        </Callout>
        {q.loading && !q.data ? (
          <Skeleton className="h-48" />
        ) : q.error ? (
          <ErrorState error={q.error} onRetry={q.refresh} />
        ) : !q.data?.length ? (
          <EmptyState title="No preview" />
        ) : numeric ? (
          <div className="h-56">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart data={q.data} margin={{ top: 8, right: 12, bottom: 0, left: 0 }}>
                <CartesianGrid stroke={CHART.grid} vertical={false} />
                <XAxis dataKey="cycle" {...axisProps} minTickGap={24} />
                <YAxis {...axisProps} width={52} domain={['auto', 'auto']} tickFormatter={(v: number) => fmt(v, 4)} />
                <Tooltip
                  cursor={{ stroke: CHART.axis, strokeDasharray: '3 3' }}
                  content={({ active, payload }) => {
                    const p = active && payload?.[0]?.payload
                    return p ? <ChartTooltip title={`simulated cycle ${p.cycle}`} rows={[{ label: stream.unit ?? 'value', value: p.value }]} /> : null
                  }}
                />
                <Line dataKey="value" stroke={CHART.line} strokeWidth={2} dot={false} isAnimationActive={false} />
              </LineChart>
            </ResponsiveContainer>
          </div>
        ) : (
          <CodeBlock maxHeight="max-h-56">{JSON.stringify(q.data.slice(0, 20), null, 2)}</CodeBlock>
        )}
      </div>
    </Card>
  )
}

export function DataSourcesPage() {
  const catalog = useApi(api.catalog, ['catalog'])
  const [query, setQuery] = useState('')
  const [selectedId, setSelectedId] = useState<string>()
  const streams = useMemo(() => catalog.data?.streams ?? [], [catalog.data])
  const filtered = useMemo(() => {
    const q = query.toLowerCase()
    return streams.filter((s) => !q || [s.id, s.name, s.modality, s.source].some((x) => x.toLowerCase().includes(q)))
  }, [streams, query])
  // Group by asset prefix (press3.*, motor4.*, …) as named in plant/catalog.yaml.
  const groups = useMemo(() => {
    const out = new Map<string, StreamInfo[]>()
    for (const s of filtered) {
      const g = s.id.includes('.') ? s.id.split('.')[0] : 'other'
      out.set(g, [...(out.get(g) ?? []), s])
    }
    return [...out.entries()]
  }, [filtered])
  const selected = streams.find((s) => s.id === selectedId) ?? filtered[0]

  return (
    <>
      <PageHeader
        title="Data sources"
        description="The plant catalog Assembly discovers data from: sensor and camera streams plus label sources (plant/catalog.yaml)."
      />
      <PageBody className="space-y-6">
        {catalog.loading && !catalog.data ? (
          <div className="grid gap-6 lg:grid-cols-[360px_1fr]">
            <Skeleton className="h-96" />
            <Skeleton className="h-96" />
          </div>
        ) : catalog.error && !catalog.data ? (
          <Card>
            <ErrorState error={catalog.error} onRetry={catalog.refresh} />
          </Card>
        ) : (
          <>
            <div className="grid gap-6 lg:grid-cols-[360px_minmax(0,1fr)]">
              <Card className="flex max-h-[720px] flex-col self-start">
                <div className="border-b border-line p-3">
                  <div className="relative">
                    <Search className="absolute top-1/2 left-2.5 size-3.5 -translate-y-1/2 text-fg-subtle" />
                    <input value={query} onChange={(e) => setQuery(e.target.value)} placeholder={`Filter ${streams.length} streams…`} className={cn(inputClass, 'pl-8')} />
                  </div>
                </div>
                <div className="min-h-0 flex-1 overflow-y-auto">
                  {groups.length === 0 && <EmptyState title="No matching streams" />}
                  {groups.map(([g, items]) => (
                    <div key={g}>
                      <div className="sticky top-0 bg-surface px-4 pt-3 pb-1 text-[11px] font-medium tracking-wide text-fg-subtle uppercase">
                        {g} <span className="font-normal">· {items.length}</span>
                      </div>
                      {items.map((s) => {
                        const Icon = MODALITY_ICON[s.modality] ?? Activity
                        return (
                          <button
                            key={s.id}
                            onClick={() => setSelectedId(s.id)}
                            className={cn(
                              'flex w-full items-center gap-2.5 px-4 py-2 text-left transition-colors hover:bg-surface-2',
                              selected?.id === s.id && 'bg-surface-2',
                            )}
                          >
                            <Icon className="size-3.5 shrink-0 text-fg-subtle" />
                            <div className="min-w-0 flex-1">
                              <div className="truncate text-xs text-fg">{s.name}</div>
                              <div className="truncate font-mono text-[10.5px] text-fg-subtle">{s.id}</div>
                            </div>
                            {s.unit && <span className="shrink-0 text-[10.5px] text-fg-subtle">{s.unit}</span>}
                          </button>
                        )
                      })}
                    </div>
                  ))}
                </div>
              </Card>
              {selected ? (
                <StreamPreview key={selected.id} stream={selected} />
              ) : (
                <Card>
                  <EmptyState icon={<Database className="size-5" />} title="No streams in the catalog" />
                </Card>
              )}
            </div>

            <Card>
              <CardHeader title="Label sources" icon={<Tag className="size-4" />} description="Ground truth the agent can build targets from" />
              {catalog.data?.label_sources.length ? (
                <div className="grid gap-px bg-line sm:grid-cols-2 xl:grid-cols-3">
                  {catalog.data.label_sources.map((l) => (
                    <div key={l.id} className="bg-surface p-4">
                      <div className="flex items-center justify-between gap-2">
                        <span className="text-sm text-fg">{l.name}</span>
                        <Badge>{l.kind}</Badge>
                      </div>
                      <Mono className="text-fg-subtle">{l.id}</Mono>
                      <p className="mt-1.5 text-xs leading-relaxed text-fg-muted">{l.description}</p>
                    </div>
                  ))}
                </div>
              ) : (
                <EmptyState title="No label sources" />
              )}
            </Card>
            <p className="text-xs text-fg-subtle">
              The catalog is configured on the server. Uploading new factory data from the UI is not supported.
            </p>
          </>
        )}
      </PageBody>
    </>
  )
}
