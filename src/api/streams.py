"""Plant catalog + previews of the REAL data behind each stream (what the agent sees during design).

Preview by data kind:
    table    one unit's full history (C-MAPSS: run to failure), plus its failure cycle from the maintenance log
    signal   the first 50 ms of the first recording (CWRU vibration)
    images   the first n images of the camera stream, served by GET /streams/{id}/images/{i}
Distractor streams are generated by design (catalog source 'synthetic') and say so. If a dataset isn't downloaded,
the preview falls back to plant/simulator.py and is marked synthetic.
"""

import asyncio
from pathlib import Path

from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse

from ml import api as ml_api
from ml import catalog
from plant import simulator

router = APIRouter(prefix="/streams", tags=["streams"])

SIGNAL_PREVIEW_S = 0.05
MAX_TABLE_POINTS = 400
MAX_IMAGES = 24


@router.get("")
async def list_streams() -> dict:
    streams, labels = ml_api.list_catalog()
    return {"streams": streams, "label_sources": labels}


def _known(stream_id: str) -> None:
    if stream_id not in {s.id for s in ml_api.list_catalog()[0]}:
        raise HTTPException(404, "unknown stream")


def _table_preview(stream_id: str, n: int) -> dict:
    df = catalog.read_stream(stream_id)
    unit = df["entity"].iloc[0]
    part = df[df["entity"] == unit].sort_values("time").head(min(n, MAX_TABLE_POINTS))
    synthetic = catalog.source_of(stream_id).startswith("synthetic:")
    failure = None
    if not synthetic:
        try:
            events = catalog.read_labels("maintenance_log")
            hit = events[events["entity"] == unit]
            failure = int(hit["event_time"].iloc[0]) if len(hit) else None
        except Exception:  # noqa: BLE001 - the label source is optional context for the preview
            failure = None
    note = (f"Unit {unit}: {len(part)} cycles" + (f", fails at cycle {failure}" if failure is not None else "")
            + (" (generated distractor stream, unrelated to failures)" if synthetic else ""))
    return {"kind": "table", "synthetic": synthetic, "note": note, "x_label": "cycle", "failure_x": failure,
            "points": [{"x": int(t), "value": round(float(v), 4)} for t, v in zip(part["time"], part[stream_id], strict=True)]}


def _signal_preview(stream_id: str) -> dict:
    idx = catalog.read_stream(stream_id)
    rec = idx.iloc[0]
    wave = catalog.load_signal(rec["path"], rec["channel"])
    hz = float(rec.get("sample_hz") or 12000)
    k = max(1, int(SIGNAL_PREVIEW_S * hz))
    step = max(1, k // 600)
    pts = [{"x": round(i / hz * 1000, 3), "value": round(float(wave[i]), 5)} for i in range(0, min(k, len(wave)), step)]
    meta = {c: rec[c] for c in ("load_hp", "rpm") if c in rec and rec[c] == rec[c]}
    note = (f"Recording {rec['record_id']}: first {SIGNAL_PREVIEW_S * 1000:.0f} ms of {len(wave) / hz:.1f} s at "
            f"{hz / 1000:g} kHz" + "".join(f", {k} {v}" for k, v in meta.items()) + f" ({len(idx)} recordings)")
    return {"kind": "signal", "synthetic": False, "note": note, "x_label": "ms", "points": pts}


def _image_preview(stream_id: str, n: int) -> dict:
    idx = catalog.read_stream(stream_id)
    k = min(n, MAX_IMAGES, len(idx))
    return {"kind": "images", "synthetic": False, "note": f"First {k} of {len(idx)} images (labels are not shown)",
            "images": [{"index": i, "record_id": idx["record_id"].iloc[i], "url": f"/api/streams/{stream_id}/images/{i}"}
                       for i in range(k)]}


def _preview(stream_id: str, n: int) -> dict:
    kind = catalog.stream_kind(stream_id)
    if kind == "table":
        return _table_preview(stream_id, n)
    if kind == "signal":
        return _signal_preview(stream_id)
    return _image_preview(stream_id, n)


@router.get("/{stream_id}/preview")
async def preview(stream_id: str, n: int = 120) -> dict:
    _known(stream_id)
    try:
        return await asyncio.to_thread(_preview, stream_id, n)
    except (FileNotFoundError, OSError, KeyError) as e:  # dataset not downloaded on this server
        pts = simulator.preview(stream_id, min(n, MAX_TABLE_POINTS))
        return {"kind": "table", "synthetic": True, "x_label": "cycle", "failure_x": None,
                "note": f"Dataset not available on this server ({type(e).__name__}); simulated values",
                "points": [{"x": p["cycle"], "value": p["value"]} for p in pts if isinstance(p["value"], (int, float))]}


@router.get("/{stream_id}/images/{index}")
async def image(stream_id: str, index: int) -> FileResponse:
    _known(stream_id)
    if catalog.stream_kind(stream_id) == "table" or catalog.stream_kind(stream_id) == "signal":
        raise HTTPException(404, "not an image stream")
    idx = await asyncio.to_thread(catalog.read_stream, stream_id)
    if not 0 <= index < min(len(idx), MAX_IMAGES):
        raise HTTPException(404, "unknown image")
    path = Path(idx["path"].iloc[index])
    if not path.is_file():
        raise HTTPException(404, "image file missing")
    return FileResponse(path)
